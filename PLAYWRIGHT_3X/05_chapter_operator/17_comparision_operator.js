
// comparison operator
// =  assignment operator is used to assign a value to a variable. The assignment operator is represented by the equal sign (=).
// == loose equality operator is used to compare two values for equality. It returns true if the values are equal, and false otherwise. The loose equality operator is represented by the double equal sign (==).
// ===  strict equality operator is used to compare two values for equality. It returns true if the values are equal and of the same type, and false otherwise. The strict equality operator is represented by the triple equal sign (===).


//>,<, <= ,>=

console.log(10>5);
console.log(10<5);
console.log(10>=5);
console.log(10<=5);

console.log(10=="5");

console.log(10==="5");
// === strict check will check the both  data type and value

//== loose check will check only the value not the data type

console.log(10==10);
console.log(10===10);

console.log(10 !="10");

console.log(10 !=="10");

console.log(10 ===10);